#!/usr/bin/env python3
"""Validate that an Eagle3 Slurm resource profile reaches pipeline dry-run.

This is no-submit. It sources/parses the profile generated by
probe_eagle3_slurm_capacity.py, runs submit_eagle3_pipeline.sh in SUBMIT=false
mode, and checks that the printed sbatch commands use the profiled GPU counts
and TP values instead of stale defaults.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shlex
import subprocess
import time
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[2]
EXP = ROOT / "experiments/eagle3_qwen3_235b"
DEFAULT_ARTIFACT_ROOT = Path("/lustre/fsw/portfolios/coreai/users/sna/qwen3_235b_eagle3")
DEFAULT_CONTAINER = "/lustre/fs1/portfolios/llmservice/projects/llmservice_deci_llm/containers/nemo_25.07.01.sqsh"
EXPORT_RE = re.compile(r"^export\s+([A-Za-z_][A-Za-z0-9_]*)=(.*)$")


def parse_args() -> argparse.Namespace:
    root = Path(os.environ.get("ARTIFACT_ROOT", DEFAULT_ARTIFACT_ROOT))
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--artifact-root", type=Path, default=root)
    parser.add_argument(
        "--resource-profile-env",
        type=Path,
        default=Path(os.environ.get("SLURM_CAPACITY_ENV", root / "reports/eagle3_resource_profile.env")),
    )
    parser.add_argument("--sbatch-account", default=os.environ.get("SBATCH_ACCOUNT", "coreai_dlalgo_nemorl"))
    parser.add_argument("--sbatch-partition", default=os.environ.get("SBATCH_PARTITION", "batch"))
    parser.add_argument("--modelopt-dir", type=Path, default=Path(os.environ.get("MODELOPT_DIR", ROOT / "Model-Optimizer")))
    parser.add_argument(
        "--input-data",
        type=Path,
        default=Path(os.environ.get("INPUT_DATA", root / "data/qwen3_235b_swe_rollout_conversations.jsonl")),
    )
    parser.add_argument("--hidden-states-dir", type=Path, default=Path(os.environ.get("HIDDEN_STATES_DIR", root / "hidden_states")))
    parser.add_argument("--output-dir", type=Path, default=Path(os.environ.get("OUTPUT_DIR", root / "modelopt_ckpt")))
    parser.add_argument("--export-dir", type=Path, default=Path(os.environ.get("EXPORT_DIR", root / "exported_hf")))
    parser.add_argument("--vllm-draft-dir", type=Path, default=Path(os.environ.get("VLLM_DRAFT_DIR", root / "vllm_draft")))
    parser.add_argument("--verifier-config-dir", type=Path, default=Path(os.environ.get("VERIFIER_CONFIG_DIR", root / "verifier_config")))
    parser.add_argument("--chat-template", type=Path, default=Path(os.environ.get("CHAT_TEMPLATE", root / "templates/qwen3_generation_template.jinja2")))
    parser.add_argument("--reference-arch", type=Path, default=Path(os.environ.get("REFERENCE_ARCH", root / "architecture/eagle3_architecture.json")))
    parser.add_argument("--arch-env-file", type=Path, default=Path(os.environ.get("ARCH_ENV_FILE", root / "architecture/eagle3_architecture.env")))
    parser.add_argument("--container", default=os.environ.get("CONTAINER") or DEFAULT_CONTAINER)
    parser.add_argument("--mounts", default=os.environ.get("MOUNTS", f"/lustre:/lustre,{ROOT}:{ROOT},{root}:{root}"))
    parser.add_argument("--json-out", type=Path)
    parser.add_argument("--markdown-out", type=Path)
    parser.add_argument("--fail-on-warn", action="store_true")
    return parser.parse_args()


def add(checks: list[dict[str, Any]], area: str, name: str, status: str, detail: str, **evidence: Any) -> None:
    checks.append({"area": area, "name": name, "status": status, "detail": detail, "evidence": evidence})


def parse_profile(path: Path) -> tuple[dict[str, str], str | None]:
    if not path.exists():
        return {}, f"not visible: {path}"
    env: dict[str, str] = {}
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except Exception as exc:
        return {}, f"cannot read: {exc}"
    for raw in lines:
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        match = EXPORT_RE.match(line)
        if not match:
            continue
        key, value = match.groups()
        try:
            parsed = shlex.split(value)
        except ValueError:
            parsed = [value]
        env[key] = parsed[0] if parsed else ""
    return env, None


def run_pipeline(args: argparse.Namespace, profile_env: dict[str, str]) -> dict[str, Any]:
    env = os.environ.copy()
    reference_arch = args.reference_arch if args.reference_arch.exists() else EXP / "qwen3_235b_thinking_eagle3_architecture.json"
    arch_env_file = str(args.arch_env_file) if args.arch_env_file.exists() else ""
    env.update(
        {
            "SUBMIT": "false",
            "RUN_PILOT": "true",
            "SBATCH_ACCOUNT": args.sbatch_account,
            "SBATCH_PARTITION": args.sbatch_partition,
            "ARTIFACT_ROOT": str(args.artifact_root),
            "INPUT_DATA": str(args.input_data),
            "HIDDEN_STATES_DIR": str(args.hidden_states_dir),
            "OUTPUT_DIR": str(args.output_dir),
            "TRAINED_CKPT": str(args.output_dir),
            "EXPORT_DIR": str(args.export_dir),
            "VLLM_DRAFT_DIR": str(args.vllm_draft_dir),
            "VERIFIER_CONFIG_DIR": str(args.verifier_config_dir),
            "CHAT_TEMPLATE": str(args.chat_template),
            "MODELOPT_DIR": str(args.modelopt_dir),
            "REFERENCE_ARCH": str(reference_arch),
            "ARCH_ENV_FILE": arch_env_file,
            "CONTAINER": args.container,
            "MOUNTS": args.mounts,
            "RESOURCE_PROFILE_ENV": str(args.resource_profile_env),
            "RUN_TRAINED_DRAFT_SMOKE": "false",
            "RUN_TRAINED_DRAFT_SWEEP": "false",
        }
    )
    result = subprocess.run(
        ["bash", "experiments/eagle3_qwen3_235b/submit_eagle3_pipeline.sh"],
        cwd=ROOT,
        env=env,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        check=False,
    )
    return {
        "returncode": result.returncode,
        "output": result.stdout,
        "output_tail": result.stdout[-12000:],
    }


def contains_line_value(output: str, key: str, value: str) -> bool:
    return f"{key}={value}" in output


def build_payload(args: argparse.Namespace) -> dict[str, Any]:
    checks: list[dict[str, Any]] = []
    profile_env, error = parse_profile(args.resource_profile_env)
    if error:
        add(checks, "profile", "resource profile env", "missing", error, path=str(args.resource_profile_env))
    else:
        add(checks, "profile", "resource profile env", "pass", "resource profile env is readable", path=str(args.resource_profile_env))

    required_keys = ["DUMP_GPUS_PER_NODE", "TRAIN_GPUS_PER_NODE", "TP"]
    for key in required_keys:
        value = profile_env.get(key)
        if value:
            add(checks, "profile", key, "pass", "profile key is set", value=value)
        else:
            add(checks, "profile", key, "fail", "profile key is missing")

    if profile_env:
        result = run_pipeline(args, profile_env)
    else:
        result = {"returncode": 1, "output": "", "output_tail": "skipped: no resource profile env"}
    output = str(result.get("output") or "")
    if result.get("returncode") == 0:
        add(checks, "dry_run", "submit_eagle3_pipeline.sh", "pass", "pipeline dry-run returned zero")
    else:
        add(
            checks,
            "dry_run",
            "submit_eagle3_pipeline.sh",
            "fail",
            "pipeline dry-run returned nonzero",
            returncode=result.get("returncode"),
            output_tail=result.get("output_tail"),
        )

    expected_dump = profile_env.get("DUMP_GPUS_PER_NODE")
    expected_train = profile_env.get("TRAIN_GPUS_PER_NODE")
    expected_export = profile_env.get("EXPORT_GPUS_PER_NODE", "1")
    expected_tp = profile_env.get("TP")
    expected_markers = {
        "dump sbatch --gres": f"--gres=gpu:{expected_dump}" if expected_dump else None,
        "train sbatch --gres": f"--gres=gpu:{expected_train}" if expected_train else None,
        "export sbatch --gres": f"--gres=gpu:{expected_export}" if expected_export else None,
        "summary DUMP_GPUS_PER_NODE": f"DUMP_GPUS_PER_NODE={expected_dump}" if expected_dump else None,
        "summary TRAIN_GPUS_PER_NODE": f"TRAIN_GPUS_PER_NODE={expected_train}" if expected_train else None,
        "summary EXPORT_GPUS_PER_NODE": f"EXPORT_GPUS_PER_NODE={expected_export}" if expected_export else None,
        "summary TP": f"TP={expected_tp}" if expected_tp else None,
    }
    for name, marker in expected_markers.items():
        if marker and marker in output:
            add(checks, "dry_run", name, "pass", "expected marker is present", marker=marker)
        else:
            add(checks, "dry_run", name, "fail", "expected marker is missing", marker=marker)

    if expected_dump and expected_dump != "8" and "--gres=gpu:8" in output:
        add(checks, "dry_run", "stale 8-GPU request", "fail", "dry-run still contains --gres=gpu:8")
    else:
        add(checks, "dry_run", "stale 8-GPU request", "pass", "dry-run does not contain stale 8-GPU request")

    counts: dict[str, int] = {}
    for check in checks:
        counts[check["status"]] = counts.get(check["status"], 0) + 1
    if counts.get("fail"):
        overall = "fail"
    elif counts.get("missing"):
        overall = "incomplete"
    elif counts.get("warn"):
        overall = "warn"
    else:
        overall = "pass"

    return {
        "generated_at": time.strftime("%Y-%m-%d %H:%M:%S %Z"),
        "overall_status": overall,
        "artifact_root": str(args.artifact_root),
        "resource_profile_env": str(args.resource_profile_env),
        "profile_env": profile_env,
        "counts": counts,
        "checks": checks,
        "dry_run": {
            "returncode": result.get("returncode"),
            "output_tail": result.get("output_tail"),
        },
    }


def render_markdown(payload: dict[str, Any]) -> str:
    lines = [
        "# Eagle3 Resource Profile Application Validation",
        "",
        f"Overall: **{payload['overall_status'].upper()}**",
        f"Profile env: `{payload['resource_profile_env']}`",
        "",
        "| area | check | status | detail |",
        "| --- | --- | --- | --- |",
    ]
    for check in payload["checks"]:
        detail = str(check["detail"]).replace("|", "/").replace("\n", " ")
        lines.append(f"| {check['area']} | {check['name']} | {check['status'].upper()} | {detail} |")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    args = parse_args()
    payload = build_payload(args)
    markdown = render_markdown(payload)
    print(markdown, end="")
    if args.json_out:
        args.json_out.parent.mkdir(parents=True, exist_ok=True)
        args.json_out.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    if args.markdown_out:
        args.markdown_out.parent.mkdir(parents=True, exist_ok=True)
        args.markdown_out.write_text(markdown, encoding="utf-8")
    if payload["overall_status"] == "fail":
        return 1
    if args.fail_on_warn and payload["overall_status"] == "warn":
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

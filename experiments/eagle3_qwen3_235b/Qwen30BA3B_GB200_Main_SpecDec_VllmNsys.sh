else
  DRIVER_ENV_ROOT="${SCRIPT_PATH_DIR}"
fi
DRIVER_UV_PROJECT_ENVIRONMENT="${DRIVER_UV_PROJECT_ENVIRONMENT:-${DRIVER_ENV_ROOT}/.driver_venvs/qwen30ba3b_specdec_vllm_nsys_py312}"

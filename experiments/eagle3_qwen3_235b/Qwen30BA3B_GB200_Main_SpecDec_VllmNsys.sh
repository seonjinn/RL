export MAX_STEPS
export NRL_NSYS_PROFILE_STEP_RANGE
export NRL_NSYS_WORKER_PATTERNS
export NRL_FORCE_REBUILD_VENVS
export NRL_VLLM_DISABLE_LOG_STATS
export NRL_VLLM_OMIT_GENERATION_LOGPROBS
export RAY_LOG_SYNC_FREQUENCY
export DRIVER_UV_PROJECT_ENVIRONMENT
export JOB_TAG
export WANDB_NAME

exec bash "${BASE_SCRIPT}"
